//! Lexical tokens (ported from go.starlark.net/syntax/scan.go).

use std::fmt;

/// A Token is a lexical token. The declaration order matches the Go
/// original, so that the comparison and arithmetic operators keep the same
/// relative order as their opcodes and augmented-assignment forms.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
