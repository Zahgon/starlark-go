    /// Like `name`, but quotes punctuation tokens (Go's Token.GoString,
    /// used by `%#v` in parser error messages).
    pub fn go_string(self) -> String {
        if self >= Token::Plus && self <= Token::Starstar {
            format!("'{}'", self.name())
        } else {
            self.name().to_string()
        }
    }

    /// Returns the keyword token spelled `s`, if any.
    pub fn keyword(s: &[u8]) -> Option<Token> {
        let t = match s {
            b"and" => Token::And,
            b"break" => Token::Break,
            b"continue" => Token::Continue,
            b"def" => Token::Def,
            b"elif" => Token::Elif,
            b"else" => Token::Else,
            b"for" => Token::For,
            b"if" => Token::If,
            b"in" => Token::In,
            b"lambda" => Token::Lambda,
            b"load" => Token::Load,
            b"not" => Token::Not,
            b"or" => Token::Or,
            b"pass" => Token::Pass,
            b"return" => Token::Return,
            b"while" => Token::While,
            b"as" => Token::As,
            b"async" => Token::Async,
            b"await" => Token::Await,
            b"class" => Token::Class,
            b"del" => Token::Del,
            b"except" => Token::Except,
            b"finally" => Token::Finally,
            b"from" => Token::From,
            b"global" => Token::Global,
            b"import" => Token::Import,
            b"is" => Token::Is,
            b"nonlocal" => Token::Nonlocal,
            b"raise" => Token::Raise,
            b"try" => Token::Try,
            b"with" => Token::With,
            b"yield" => Token::Yield,
            _ => return None,
        };
        Some(t)
    }
